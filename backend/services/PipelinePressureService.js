// ─── Deal velocity ────────────────────────────────────────────────────────────

const VELOCITY_THRESHOLDS = {
  discovery:      14,
  due_diligence:  30,
  financing:      30,
};

export function checkDealVelocity(deals) {
  return (deals || [])
    .filter((d) => d.stage !== 'closed' && d.stage !== 'lost')
    .map((d) => {
      const days      = d.stageEnteredAt ? daysSinceDate(d.stageEnteredAt) : daysSinceDate(d.updatedAt);
      const threshold = VELOCITY_THRESHOLDS[d.stage] ?? null;
      return {
        dealId:          d.id,
        companyName:     d.companyName,
        stage:           d.stage,
        stageDurationDays: days,
        threshold,
        slowMoving:      threshold !== null && days > threshold,
      };
    });
}

